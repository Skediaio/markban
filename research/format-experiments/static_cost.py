#!/usr/bin/env python3
"""Static cost analysis -> results/static.md.

READ  full = bytes of every file an agent reads in full to do the task safely.
READ  grep = oracle lower bound: only the lines that are strictly needed (grep/sed output, with a
             `path:` prefix per line for multi-file greps), assuming ids follow the slug rule.
WRITE      = bytes of the edit payloads: replace = len(old)+len(new), create = len(new),
             delete = len("rm <path>"). Task 1 writes answer.txt (same for all formats).
Tokens ~ bytes / 3.8.
"""
import os
import re

import ops
from common import HERE, build_model, render

TOK = 3.8
sz = lambda s: len(s.encode())
fmt_cell = lambda b: f"{b} (~{round(b / TOK)})"


def grep(fs, paths, rx):
    r = re.compile(rx)
    return sum(sz(p) + 1 + sz(l) + 1 for p in paths for l in fs[p].split("\n") if r.search(l))


def lines(text, rx):
    r = re.compile(rx, re.M)
    return sum(sz(m.group(0)) + 1 for m in r.finditer(text))


def cards(fs):
    return sorted(p for p in fs if p.startswith("cards/"))


def b_col_files(fs, col):
    return [p for p in cards(fs) if f"\ncolumn: {col}\n" in fs[p]]


def reads(fmt, fs, n):
    """Return (full, grep) bytes for task n (2..7); task 1 handled by caller."""
    full = lambda ps: sum(sz(fs[p]) for p in ps)
    if fmt == "A":
        b = fs["board.md"]
        if n == 1:
            sec = re.search(r"^## Doing\n.*?(?=^## )", b, re.M | re.S).group(0)
            return sz(b), sz(sec)
        g = {2: lines(b, r"^- \[Fix login timeout\].*$|^## Done$"), 3: lines(b, r"^## Ready$"),
             4: lines(b, r"^## Review$"), 5: lines(b, r"^- \[(Audit log|Rate limiter)\].*$"),
             6: lines(b, r"^- \[Old prototype\].*$"),
             7: sz(fs["cards/payment-webhooks.md"].rstrip("\n").split("\n")[-1]) + 1}
        f = {7: full(["cards/payment-webhooks.md"])}
        return f.get(n, sz(b)), g[n]
    if fmt == "B":
        allc = cards(fs)
        if n == 1:
            ds = b_col_files(fs, "doing")
            return full(allc), grep(fs, allc, r"^column: doing$") + grep(fs, ds, r"^(title|order):")
        if n in (2, 3, 5):
            col = {2: "done", 3: "backlog", 5: "backlog"}[n]
            cs = b_col_files(fs, col)
            g = grep(fs, allc, rf"^column: {col}$") + grep(fs, cs, r"^order:")
            if n == 2:
                g += grep(fs, ["cards/fix-login-timeout.md"], r"^(column|order):")
            if n == 5:
                g += grep(fs, ["cards/audit-log.md"], r"^(column|order):")
            return full(allc), g
        if n == 4:
            return sz(fs["board.md"]), grep(fs, ["board.md"], r"name: Review$")
        if n == 6:
            return full(["cards/old-prototype.md"]), 0
        return full(["cards/payment-webhooks.md"]), sz(fs["cards/payment-webhooks.md"].rstrip("\n").split("\n")[-1]) + 1
    b = fs["board.md"]
    blk = lambda cid: ops.c_block(b, cid)[1]
    if n == 1:
        return sz(b), lines(b, r"^#{2,3} .*$")
    g = {2: sz(blk("fix-login-timeout")) + lines(b, r"^## Done$"), 3: lines(b, r"^## Ready$"),
         4: lines(b, r"^## Review$"), 5: sz(blk("audit-log")), 6: sz(blk("old-prototype")),
         7: sz(blk("payment-webhooks").rstrip("\n").split("\n")[-1]) + 1}
    return sz(b), g[n]


def write_cost(es):
    t = 0
    for p, old, new in es:
        t += sz(new) if old is None else sz("rm " + p) if new is None else sz(old) + sz(new)
    return t


def main():
    model = build_model()
    tops = ops.task_ops(model)
    answer = sum(sz(c["title"]) + 1 for c in model["cards"] if c["column"] == "doing")
    rules = {f: os.path.getsize(os.path.join(HERE, f"RULES-{f}.md")) for f in "ABC"}
    res, info = {}, {}
    for f in "ABC":
        fs = render(f, model)
        info[f] = (len(fs), sum(sz(t) for t in fs.values()), sz(fs["board.md"]))
        for n in range(1, 8):
            r, g = reads(f, fs, n)
            w = answer if n == 1 else write_cost(ops.edits(f, {p: fs.get(p) for p in ops.needs(f, tops[n], fs)}, tops[n]))
            res[f, n] = (r, g, w)
    out = ["# Static cost analysis", "",
           "Generated by `static_cost.py`. Cells are `bytes (~tokens)`, tokens = bytes/3.8.",
           "READ full = files read in full; READ grep = oracle lower bound (only needed lines, `path:` prefix per grep line);",
           "WRITE = edit payload bytes (old+new for replaces, new for creates, `rm path` for deletes).", "",
           "## Fixture sizes", "", "| format | files | total bytes | board.md bytes |", "|---|---|---|---|"]
    out += [f"| {f} | {info[f][0]} | {info[f][1]} | {info[f][2]} |" for f in "ABC"]
    out += ["", "## Per task", "", "| task | A read full | A read grep | A write | B read full | B read grep | B write | C read full | C read grep | C write |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for n in range(1, 8):
        out.append(f"| {n} | " + " | ".join(fmt_cell(v) for f in "ABC" for v in res[f, n]) + " |")
    out += ["", "## Totals over the 7 tasks", "",
            "| format | read full | read grep | write | RULES file | total full (read+write+rules) | total grep (read+write+rules) |",
            "|---|---|---|---|---|---|---|"]
    for f in "ABC":
        r = sum(res[f, n][0] for n in range(1, 8)); g = sum(res[f, n][1] for n in range(1, 8))
        w = sum(res[f, n][2] for n in range(1, 8))
        out.append(f"| {f} | {fmt_cell(r)} | {fmt_cell(g)} | {fmt_cell(w)} | {fmt_cell(rules[f])} | "
                   f"{fmt_cell(r + w + rules[f])} | {fmt_cell(g + w + rules[f])} |")
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    with open(os.path.join(HERE, "results", "static.md"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
