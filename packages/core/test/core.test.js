import { mkdtempSync, mkdirSync, writeFileSync, symlinkSync, rmSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterEach, describe, expect, it } from 'vitest';
import { card, check, init, loadBoard, openBoard, parseBoard, readBoardFiles, search } from '../src/index.node.js';

const here = fileURLToPath(new URL('.', import.meta.url));
const demo = join(here, '../../../examples/demo-board');
const messy = join(here, 'fixtures/messy-board');

/** The exact output of `markban ls --json`, generated by the CLI. */
const fixture = (/** @type {string} */ name) =>
  JSON.parse(readFileSync(join(here, 'fixtures', name), 'utf8'));

describe('loadBoard', () => {
  it('equals `markban ls --json` for examples/demo-board', () => {
    expect(loadBoard(demo)).toEqual(fixture('demo-board.ls.json'));
  });

  it('equals `markban ls --json` for a board with problems, diagnostics included', () => {
    const view = loadBoard(messy);
    expect(view).toEqual(fixture('messy-board.ls.json'));
    expect(view.diagnostics.map((d) => d.code)).toEqual(['E007', 'E008', 'E006', 'W001', 'W001']);
  });

  it('throws a clear error for something that is not a directory', () => {
    expect(() => loadBoard(join(here, 'nope'))).toThrow(/is not a directory/);
  });
});

describe('API on in-memory files', () => {
  const files = readBoardFiles(demo).files;

  it('parseBoard, card and check agree with each other', () => {
    expect(parseBoard(files)).toEqual(fixture('demo-board.ls.json'));
    expect(check(files)).toEqual([]);
    expect(card(files, '0001-spec-draft')).toMatchObject({
      id: '0001-spec-draft',
      title: 'Write spec v0.1',
      column: 'done',
    });
    expect(card(files, 'missing')).toBeNull();
  });

  it('init() is a no-op in Node', async () => {
    await expect(init()).resolves.toBeUndefined();
  });

  it('a missing board.md is a diagnostic, not an exception', () => {
    const view = parseBoard([{ path: 'cards/a.md', content: '---\ntitle: A\n---\n' }]);
    expect(view.columns).toEqual([]);
    expect(view.diagnostics.map((d) => d.code)).toEqual(['E001']);
  });

  it('rejects input that is not a file list', () => {
    // @ts-expect-error deliberately wrong
    expect(() => parseBoard('nope')).toThrow(/files must be an array/);
  });
});

describe('archived cards', () => {
  const files = readBoardFiles(demo).files;

  it('parseBoard lists them in `archived` (id order), not in columns or unsorted', () => {
    const view = parseBoard(files);
    expect(view.archived.map((c) => c.id)).toEqual(['0004-research']);
    const shown = [
      ...view.columns.flatMap((c) => c.cards.map((card) => card.id)),
      ...view.unsorted.map((card) => card.id),
    ];
    expect(shown).not.toContain('0004-research');
  });

  it('card() sets archived: true for them and leaves the flag out for active cards', () => {
    expect(card(files, '0004-research')?.archived).toBe(true);
    expect('archived' in (card(files, '0001-spec-draft') ?? {})).toBe(false);
  });

  it('a board without archived cards has an empty list', () => {
    const view = parseBoard([{ path: 'board.md', content: '---\nmarkban: 0.1\n---\n' }]);
    expect(view.archived).toEqual([]);
  });
});

describe('search', () => {
  const files = readBoardFiles(demo).files;

  it('AND over the terms, matching ids, titles and descriptions', () => {
    expect(search(files, ['spec', 'draft']).cards.map((c) => c.id)).toEqual(['0001-spec-draft']);
    expect(search(files, ['SPEC'])).toEqual(search(files, ['spec']), 'terms are case-insensitive');
  });

  it('flags archived hits, orders them after the active ones, and carries a snippet', () => {
    const hits = search(files, ['experiments']);
    expect(hits.cards.map((c) => c.id)).toEqual(['0001-spec-draft', '0004-research']);
    expect(hits.cards[0].archived).toBe(false);
    expect(hits.cards[1].archived).toBe(true);
    expect(hits.cards[1].column).toBe('done');
    expect(hits.cards[0].snippet).toMatchObject({
      line: 1,
      text: 'The format in `spec/SPEC.md`, chosen after the experiments in `research/format-experiments`.',
    });
  });

  it('matches columns and the board itself', () => {
    expect(search(files, ['backlog']).columns).toEqual([{ id: 'backlog', name: 'Backlog' }]);
    expect(search(files, ['backlog']).cards).toEqual([]);
    expect(search(files, ['roadmap'])).toEqual({ cards: [], columns: [], board: true });
  });

  it('empty terms give empty results', () => {
    expect(search(files, [])).toEqual({ cards: [], columns: [], board: false });
  });

  it('a board without a usable board.md gives empty results', () => {
    const hits = search([{ path: 'cards/a.md', content: '---\ntitle: A\n---\n' }], ['a']);
    expect(hits).toEqual({ cards: [], columns: [], board: false });
  });

  it('rejects terms that are not an array of strings', () => {
    // @ts-expect-error deliberately wrong
    expect(() => search(files, 'nope')).toThrow(/terms must be an array/);
  });
});

describe('symbolic links are never followed', () => {
  /** @type {string[]} */
  const dirs = [];
  afterEach(() => {
    for (const d of dirs.splice(0)) rmSync(d, { recursive: true, force: true });
  });
  const tmp = () => {
    const d = mkdtempSync(join(tmpdir(), 'markban-core-'));
    dirs.push(d);
    return d;
  };
  const boardMd = '---\nmarkban: 0.1\ntitle: T\ncolumns:\n  - id: a\n    name: A\n---\n';

  it('a card that is a link is W001 and not loaded', () => {
    const outside = tmp();
    writeFileSync(join(outside, 'secret.md'), '---\ntitle: Secret\ncolumn: a\n---\n');
    const dir = tmp();
    writeFileSync(join(dir, 'board.md'), boardMd);
    mkdirSync(join(dir, 'cards'));
    symlinkSync(join(outside, 'secret.md'), join(dir, 'cards/secret.md'));
    const view = loadBoard(dir);
    expect(JSON.stringify(view)).not.toContain('Secret');
    expect(view.diagnostics).toMatchObject([{ code: 'W001', file: 'cards/secret.md' }]);
  });

  it('a board.md that is a link counts as missing', () => {
    const outside = tmp();
    writeFileSync(join(outside, 'board.md'), boardMd);
    const dir = tmp();
    symlinkSync(join(outside, 'board.md'), join(dir, 'board.md'));
    const view = loadBoard(dir);
    expect(view.title).toBe('');
    expect(view.diagnostics.map((d) => [d.code, d.file])).toEqual([
      ['E001', 'board.md'],
      ['W001', 'board.md'],
    ]);
  });

  it('a cards directory that is a link is not read', () => {
    const outside = tmp();
    writeFileSync(join(outside, 'x.md'), '---\ntitle: Secret\ncolumn: a\n---\n');
    const dir = tmp();
    writeFileSync(join(dir, 'board.md'), boardMd);
    symlinkSync(outside, join(dir, 'cards'));
    const view = loadBoard(dir);
    expect(JSON.stringify(view)).not.toContain('Secret');
    expect(view.diagnostics).toMatchObject([{ code: 'W001', file: 'cards' }]);
  });

  it('a card that is not UTF-8 is E009', () => {
    const dir = tmp();
    writeFileSync(join(dir, 'board.md'), boardMd);
    mkdirSync(join(dir, 'cards'));
    writeFileSync(join(dir, 'cards/bad.md'), Buffer.from([0x2d, 0x2d, 0x2d, 0xff, 0xfe]));
    expect(loadBoard(dir).diagnostics).toMatchObject([{ code: 'E009', file: 'cards/bad.md' }]);
  });

  it('openBoard gives card details', () => {
    expect(openBoard(demo).card('0002-parser')?.title).toBe('Core library and CLI');
  });
});
